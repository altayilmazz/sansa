type Rule = [RegExp, string]
/** Sayı içeren metinler için kalıplar. */
const RULES: Rule[] = [
  [/^(\d+) takım$/, '$1 teams'],
  [/^(\d+) mayın$/, '$1 mines'],
  [/^(\d+) sayı$/, '$1 numbers'],
  [/^(\d+) at$/, '$1 horses'],
  [/^(\d+) mermi$/, '$1 bullets'],
  [/^(\d+) sn$/, '$1 s'],
  [/^(\d+) kayıt havuzda$/, '$1 entries in the pool'],
  [/^(\d+) \/ (\d+) kayıt çekilebilir$/, '$1 / $2 entries available'],
  [/^(\d+) mayın · (\d+) güvenli kare$/, '$1 mines · $2 safe squares'],
  [/^(\d+) \/ (\d+) hamle$/, '$1 / $2 moves'],
  [/^(\d+) hamlede mat$/, 'Checkmate in $1 moves'],
  [/^(\d+) numaralı at kazandı!?$/, 'Horse #$1 won!'],
  [/^(\d+) kez çekildi · (\d+) mermi, (\d+) yuva$/, 'Pulled $1 times · $2 bullets, $3 chambers'],
  [/^(\d+) sn içinde biri seçilecek$/, 'One will be picked within $1 s'],
  [/^(\d+) kazanan çek$/, 'Draw $1 winners'],
  [/^(\d+) sayı üret$/, 'Generate $1 numbers'],
  [/^(\d+) kazanan$/, '$1 winners'],
  [/^(\d+) kişi$/, '$1 people'],
  [/^(\d+) kayıt$/, '$1 entries'],
  [/^(\d+) takıma ayır$/, 'Split into $1 teams'],
  [/^(\d+) parmak seçildi$/, '$1 fingers picked'],
  [/^(\d+)\. oyuncu$/, 'Player $1'],
]

const cache = new Map<string, string | null>()

/** Türkçe bir metnin İngilizcesi; çevirisi yoksa null. */
export function translate(text: string): string | null {
  const hit = cache.get(text)
  if (hit !== undefined) return hit
  const core = text.trim()
  let out: string | null = null
  if (core) {
    const direct = EN[core]
    const titled = /^(.+) · Şansa$/.exec(core)
    if (direct) out = direct
    else if (titled) {
      const inner = translate(titled[1])
      out = inner ? `${inner} · Şansa` : null
    } else
      for (const [re, to] of RULES) {
        if (re.test(core)) {
          out = core.replace(re, to)
          break
        }
      }
  }
  if (out) out = text.slice(0, text.length - text.trimStart().length) + out + text.slice(text.trimEnd().length)
  cache.set(text, out)
  return out
}
